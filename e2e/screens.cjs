const { chromium } = require("playwright");
(async () => {
  const out = process.argv[2];
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("http://127.0.0.1:8765/");
  await page.waitForTimeout(500);
  await page.click("#new-draft", { force: true }).catch(() => {});
  await page.evaluate(() => document.getElementById("new-draft").click());
  await page.waitForTimeout(500);
  await page.click("#title");
  await page.keyboard.type("Voice-first interview notes");
  const say = async (t) => { await page.evaluate((t) => window.phlo.simulateSpeech(t), t); await page.waitForTimeout(1300); };
  await say("new section problem: interviews are hard to follow when you're managing a doc");
  await say("under problem: you end up managing the tool instead of the conversation");
  await say("under problem: the blank page makes it worse");
  await say("new section approach: talk, and the page organizes itself");
  await say("under approach: typing gets the same magic, nothing to click");
  await say("new section pricing: per seat for teams");
  await say("under pricing: a free tier for students");
  await say("under pricing: should solo users pay at all?");
  await page.mouse.click(10, 400);
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/10-draft.png` });
  await page.click("#role-scribe");
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/11-room.png` });
  await page.keyboard.press("Escape");
  await page.click("#role-partner");
  await page.evaluate(() => (document.documentElement.dataset.theme = "sumi"));
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${out}/12-sumi.png` });
  await page.evaluate(() => (document.documentElement.dataset.theme = "paper"));
  await page.waitForTimeout(300);
  console.log("publish ready:", await page.evaluate(() => document.getElementById("publish").classList.contains("ready")));
  await page.click("#publish");
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${out}/13-shelf.png` });
  await page.evaluate(() => document.getElementById("menu").click());
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/14-sidebar.png` });
  console.log("ERRORS", errors);
  await browser.close();
})();
