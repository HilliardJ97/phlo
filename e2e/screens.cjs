// Captures the four designed screens from the running app (npm run web first).
const { chromium } = require("playwright");
(async () => {
  const out = process.argv[2];
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
  await page.goto("http://127.0.0.1:8765/");
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${out}/01-start.png` });
  // Space on an empty draft talks (visual only here: no microphone in CI).
  console.log("focused doc on start:", await page.evaluate(() => document.activeElement?.id));
  const say = async (t) => { await page.evaluate((t) => window.phlo.simulateSpeech(t), t); await page.waitForTimeout(1200); };
  await say("new section mission: make it easier to turn meaningful moments into books people want to keep");
  await page.click("#title");
  await page.keyboard.type("Photo books worth keeping");
  await say("new section first product: a premium photo book built around one occasion");
  await say("under first product: priced around $150 to $200 per book");
  await say("scratch that, priced around $200 per book");
  await say("under first product: hardcover, linen, made to display");
  await say("new section who it's for: couples marking a year, a wedding, a first kid");
  await say("oh also, could this be a subscription, one book a year");
  await say("under who it's for: families who print one book a year");
  await say("under who it's for: grandparents who want copies");
  await say("talk to 5 couples about the price");
  await page.click("text=Couples marking a year");
  await page.evaluate(() => window.phlo.setTalking(true, false));
  await page.evaluate(() => window.phlo.simulateInterim("People who've given a Google photo book and felt it was too basic to display"));
  await page.evaluate(() => window.phlo.showAsk("Which occasion makes it worth paying for?"));
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/02-talking.png` });
  await page.evaluate(() => { window.phlo.simulateInterim(""); window.phlo.setTalking(false); });
  await page.waitForTimeout(300);
  await page.click("#role-scribe");
  await page.evaluate(() => window.phlo.setTalking(true, true));
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/03-room.png` });
  await page.evaluate(() => window.phlo.setTalking(false));
  await page.keyboard.press("Escape");
  await page.click("#role-partner");
  await page.click("#open-side");
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/04-sidebar.png` });
  const st = await page.evaluate(() => window.phlo.state());
  console.log(JSON.stringify(st.blocks.map((b) => [b.kind, b.wet ? "WET" : "", b.tab ?? "", b.text, b.trail ?? ""])));
  console.log("ERRORS", errors);
  await browser.close();
})();
